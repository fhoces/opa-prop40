#!/usr/bin/env python3
"""Render review/README.md from the review/*.json ledgers (standard library only)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "README.md"
METHOD = {"matches": "matches", "matches_with_caveat": "matches with caveat",
          "opa_definition": "OPA's own definition", "plumbing": "plumbing"}
STATE = {"understood": "reviewed", "partly": "lightly reviewed", "not_reviewed": "not reviewed"}


def one(s):
    return " ".join(str(s or "").split())


def cell(s):
    return one(s).replace("|", "\\|")


def link(loc):
    if not loc:
        return ""
    text = f"{loc['path']} {loc.get('symbol', '')} L{loc['lines'][0]}-L{loc['lines'][1]}"
    text = cell(text).replace("[", "(").replace("]", ")")
    return f"[{text}]({loc['url']})" if loc.get("url") else text


def is_open(fb):
    return not isinstance(fb, dict) or one(fb.get("status", "open")).lower() == "open"


def main():
    out = ["# Code review ledgers", "",
           "Work in progress. One ledger per OPA: the chain of code behind the headline number, "
           "top (the number on the page) to bottom (the raw data), with the reviewer's state per "
           "layer. The states are recorded during review sessions; see the review protocol in "
           "the opa-review skill.", "",
           "The three states: reviewed means the reviewer knows what goes in, what comes out "
           "and the one idea. Lightly reviewed means the layer was looked at, with what is understood so "
           "far and what is still missing written down. Not reviewed means no review yet.", ""]
    for f in sorted(p for p in HERE.glob("*.json") if not p.name.startswith("seed_")):
        d = json.loads(f.read_text(encoding="utf-8"))
        layers = d["layers"]
        h = d["headline"]
        c = {k: sum(1 for l in layers if l.get("state") == k) for k in STATE}
        out += [f"## {one(d['title'])}", "",
                f"- Headline: {one(h['label'])}, {one(h['value'])}. {one(h['definition'])}",
                f"- Where: {h['where']}",
                f"- Commit: {d['commit']}",
                f"- Seeded: {d['seeded']}",
                f"- Headline verified by: {one(d['verified_by'])}",
                f"- Runs for a stranger: {one(d['runs_for_a_stranger'])}", "",
                f"Progress: {c['understood']} of {len(layers)} reviewed, {c['partly']} lightly reviewed, "
                f"{c['not_reviewed']} not reviewed", "",
                "| Layer | Where | Method | State | Missing | Feedback | Updated |",
                "|---|---|---|---|---|---|---|"]
        for l in layers:
            where = link(l.get("r"))
            if l.get("py"):
                where += "<br>" + link(l["py"])
            meth = METHOD.get(l["method_status"], l["method_status"])
            if l.get("method_ref"):
                meth += ": " + l["method_ref"]
            nfb = sum(1 for x in l.get("feedback", []) if is_open(x))
            out.append("| " + " | ".join([
                cell(f"{l['n']}. {l['name']}"), where, cell(meth),
                STATE.get(l.get("state"), cell(l.get("state"))), cell(l.get("missing")),
                str(nfb) if nfb else "", cell(l.get("updated"))]) + " |")
        out.append("")
        for l in layers:
            if one(l.get("understanding")) or one(l.get("missing")):
                out += [f"### Layer {l['n']}, {one(l['name'])}", "",
                        f"Understood so far: {one(l.get('understanding'))}", "",
                        f"Still missing: {one(l.get('missing'))}", ""]
        items = [(l, x) for l in layers for x in l.get("feedback", [])]
        if items:
            out += ["### Feedback", ""]
            for l, x in items:
                if isinstance(x, dict):
                    out.append(f"- {x.get('date', '')}, layer {l['n']}, {x.get('status', '')}: "
                               f"{one(x.get('text'))}")
                else:
                    out.append(f"- layer {l['n']}: {one(x)}")
            out.append("")
    out += ["Generated by review/render.py from the ledgers; do not edit by hand.", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")


main()
