#!/usr/bin/env python3
"""From the files changed since a commit, the local commands that rebuild the generated pages,
and a warning for every generated file that was edited directly.

    python3 .claude/skills/opa-review-loop/tools/needs_render.py <start commit>
"""
import fnmatch
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]

# (glob of a changed source, the command that rebuilds what depends on it)
RULES = [
    ("bsz-analysis/site/repro.qmd", "cd bsz-analysis && quarto render site/repro.qmd   # needs the pipeline outputs: the workbook in original-materials/, then Rscript -e 'targets::tar_make()'"),
    ("bsz-analysis/site/materials.qmd", "cd bsz-analysis && quarto render site/materials.qmd"),
    ("bsz-analysis/site/slides/slides.Rmd", "Rscript -e 'rmarkdown::render(\"bsz-analysis/site/slides/slides.Rmd\")'"),
    ("bsz-analysis/_raw-sources.md", "bsz-analysis/tools/sync-readme.sh"),
    ("bsz-analysis/R/*", "cd bsz-analysis && Rscript -e 'targets::tar_make()' && Rscript tests/testthat.R   # needs the workbook"),
    ("bsz-analysis/py/*", "cd bsz-analysis && python py/run_export.py && Rscript tests/testthat.R   # parity"),
    ("rjkdc-analysis/site/repro.qmd", "cd rjkdc-analysis && RAUH_REPO_DIR=<clone> quarto render site/repro.qmd"),
    ("rjkdc-analysis/site/materials.qmd", "cd rjkdc-analysis && quarto render site/materials.qmd"),
    ("rjkdc-analysis/site/slides/slides.Rmd", "Rscript -e 'rmarkdown::render(\"rjkdc-analysis/site/slides/slides.Rmd\")'"),
    ("rjkdc-analysis/R/*", "cd rjkdc-analysis && RAUH_REPO_DIR=<clone> Rscript -e 'targets::tar_make()' && RAUH_REPO_DIR=<clone> Rscript tests/testthat.R"),
    ("rjkdc-analysis/py/*", "cd rjkdc-analysis && RAUH_REPO_DIR=<clone> python py/run_export.py && RAUH_REPO_DIR=<clone> Rscript tests/testthat.R   # parity"),
    ("comparison/site/index.template.html", "Rscript comparison/run.R && Rscript comparison/tests/testthat.R   # regenerates index.html; CI checks the committed page equals this output"),
    ("comparison/site/explorer.template.html", "Rscript comparison/run.R && Rscript comparison/tests/testthat.R   # regenerates comparison/site/explorer/index.html"),
    ("comparison/site/explorer/model.js", "Rscript comparison/tests/testthat.R   # model.js parity with R (needs node)"),
    ("comparison/R/*", "Rscript comparison/run.R && Rscript comparison/tests/testthat.R"),
    ("comparison/py/*", "python3 comparison/py/bridge.py && Rscript comparison/tests/testthat.R   # parity"),
    ("comparison/data/*", "Rscript comparison/run.R && Rscript comparison/tests/testthat.R"),
    ("comparison/site/repro.qmd", "cd comparison/site && quarto render repro.qmd"),
    ("comparison/site/materials.qmd", "cd comparison/site && quarto render materials.qmd"),
    ("review/*.json", "python3 review/render.py"),
]

GENERATED = {
    "index.html": "generated from comparison/site/index.template.html by Rscript comparison/run.R; CI fails unless the rebuild reproduces it byte for byte",
    "assets/comparison-data.js": "generated by Rscript comparison/run.R",
    "comparison/site/explorer/index.html": "generated from comparison/site/explorer.template.html by Rscript comparison/run.R; CI fails unless the rebuild reproduces it byte for byte",
    "*/site/repro.html": "rendered from repro.qmd by Quarto; the next render overwrites a hand edit",
    "*/site/materials.html": "rendered from materials.qmd by Quarto; the next render overwrites a hand edit",
    "*/site/slides/slides.html": "rendered from slides.Rmd; the next render overwrites a hand edit",
    "*/site/explorer/grid.js": "generated by the analysis's R pipeline; test-site.R checks it byte for byte",
    "*/site/data/*": "generated by the analysis's R pipeline",
    "*/export/*": "generated export contract",
    "review/README.md": "rendered by python3 review/render.py from review/*.json",
}


def changed(start):
    out = subprocess.run(["git", "diff", "--name-only", start], cwd=ROOT, capture_output=True, text=True).stdout
    files = set(l.strip() for l in out.splitlines() if l.strip())
    st = subprocess.run(["git", "status", "--porcelain"], cwd=ROOT, capture_output=True, text=True).stdout
    for l in st.splitlines():
        if l[:2].strip() in {"??", "A", "AM", "M", "MM", "R"} and len(l) > 3:
            files.add(l[3:].strip().split(" -> ")[-1])
    return sorted(files)


def main():
    start = sys.argv[1] if len(sys.argv) > 1 else "HEAD"
    files = changed(start)
    commands, warnings, matched = [], [], set()
    for f in files:
        for pat, cmd in RULES:
            if fnmatch.fnmatch(f, pat):
                if cmd not in commands:
                    commands.append(cmd)
                matched.add(f)
        for pat, why in GENERATED.items():
            if fnmatch.fnmatch(f, pat):
                warnings.append(f"{f}: edited directly; {why}")
    print(f"Changed files since {start}: {len(files)}")
    if commands:
        print("\nRun locally, in this order:")
        for c in commands:
            print(f"  {c}")
    else:
        print("\nNo generated page depends on the changed files.")
    if warnings:
        print("\nGenerated files changed in this run:")
        for w in warnings:
            print(f"  {w}")


if __name__ == "__main__":
    main()
