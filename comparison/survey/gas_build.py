"""Writes the Apps Script that builds the six experiment forms (pre-analysis plan, section 4.3).

Usage: python3 comparison/survey/gas_build.py ITEMS.json SOURCE_FORM_ID > build.gs

Each form is a Drive copy of the live version 1 form (so the questions and the opt-in branching are
the live ones), changed as the plan's section 4.4 says. The treatment page text and the BSZ/JR
choice labels come from mock_forms.py, which reads them from comparison/export/r/. The forms are
left closed to responses.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mock_forms as m  # noqa: E402

items = json.load(open(sys.argv[1]))
source = sys.argv[2]


def bar(x):
    return ("\u2588" if x <= 0 else "\u2591") * max(1, round(20 * abs(x) / abs(m.by_size[0][2])))


lines = [m.STUDIES_LEAD] + ["\u2022 " + s for s in m.STUDIES] + ["", m.INTRO[0], "", m.INTRO[1]]
for i, (key, t, x, hi, lo) in enumerate(m.by_size, 1):
    lines += ["", f"{i}. {t}", f"{bar(x)} {m.amount(x)}"] + ([f"BSZ: {hi}.", f"JR: {lo}."] if hi else [])
lines += ["", m.NOTE, "", m.CLOSE]
treat = {"title": "How the two estimates differ", "help": "\n".join(lines)}

labels = {}
for e in items + m.rewrite(items):
    for c in e["choices"]:
        if c[:3] in ("A. ", "B. "):
            labels[c] = m.study_label(c)

forms = [{"name": f"exp: Prop 40 survey ({g}, {arm})", "treated": arm == "treatment"}
         for g in ("landing", "explorer", "share") for arm in ("control", "treatment")]
_old = next(e for e in items if e["title"].startswith("Who has already left"))
_d, _a, _s, _w = m.split_bundle(_old)
bundle_spec = {"title": _d["title"], "map": dict(zip(_old["choices"], _d["choices"]))}
avoid_spec = {"title": _a["title"], "choices": _a["choices"]}
share_spec = {"title": _s["title"], "choices": _s["choices"]}
close_spec = {"old": m.CLOSE_PAGE_OLD, "new": m.CLOSE_PAGE, "support": m.SUPPORT_TITLE}
small_spec = {"wealth": m.WEALTH_TITLE, "old": m.SMALL_PAGE_OLD, "new": m.SMALL_PAGE,
              "optin_old": m.OPTIN_OLD, "optin": m.OPTIN}
# The questions whose two values are replaced (mock_forms.REWRITE): old text to new, in place.
_new = m.rewrite(items)
choice_specs = []
for _t in m.REWRITE:
    _nt = m.REWRITE[_t][1].get("title", _t)          # a renamed question (the court question)
    _o = next(e for e in items if e["title"] == _t)
    _n = next(e for e in _new if e["title"] == _nt)
    choice_specs.append({"title": _t, "newTitle": _nt if _nt != _t else None,
                         "map": {a: b for a, b in zip(_o["choices"], _n["choices"]) if a[:3] in ("A. ", "B. ")}})
email_spec = {"old": m.EMAIL_OLD, "title": m.EMAIL["title"], "help": m.EMAIL["help"]}
prior = "Before opening this survey, had you looked at news sources, web pages or academic studies comparing estimates of Proposition 40, the Billionaire Wealth Tax Proposal in California?"

print(f"""// Generated by comparison/survey/gas_build.py. Run buildExperiment once; it skips forms that exist.
var SOURCE_ID = {json.dumps(source)};
var FORMS = {json.dumps(forms)};
var TREAT = {json.dumps(treat)};
var LABELS = {json.dumps(labels)};
var PRIOR = {json.dumps(prior)};
var HORIZON_OLD = {json.dumps(m.HORIZON_OLD)};
var HORIZON = {json.dumps(m.HORIZON)};
var GROUPS = {json.dumps(m.GROUPS)};
var BUNDLE_PREFIX = "Who has already left";
var BUNDLE = {json.dumps(bundle_spec)};
var SHARE = {json.dumps(share_spec)};
var AVOID = {json.dumps(avoid_spec)};
var SMALL = {json.dumps(small_spec)};
var CLOSE = {json.dumps(close_spec)};
var UNSURE = {json.dumps(list(m.UNSURE))};
var CHOICES = {json.dumps(choice_specs)};
var EMAIL = {json.dumps(email_spec)};
var DESC = {json.dumps(m.DESC)};
var THANKS = {json.dumps(m.THANKS)};
var FIELD = "Which field best describes your work?";
var EXPERT = "Do you consider yourself an expert in tax or fiscal policy?";

function find_(f, title) {{
  return f.getItems().filter(function (it) {{ return it.getTitle() === title; }})[0];
}}

// The required questions in the order of the comparison page's four terms, under plain headings.
function regroup_(f) {{
  var mc = FormApp.ItemType.MULTIPLE_CHOICE;
  var start = f.getItems(FormApp.ItemType.PAGE_BREAK).filter(function (it) {{
    return it.getTitle() === "The inputs"; }})[0].getIndex() + 1;
  var seq = [];
  GROUPS.forEach(function (g) {{
    seq.push(f.addSectionHeaderItem().setTitle(g[0]));
    g[1].forEach(function (pre) {{
      var all = f.getItems();
      var q = all.filter(function (it) {{ return it.getType() === mc && it.getTitle().indexOf(pre) === 0; }});
      if (q.length !== 1) throw new Error("regroup: " + pre + " matched " + q.length);
      seq.push(q[0]);
      var next = all[q[0].getIndex() + 1];
      if (next && next.getType() === FormApp.ItemType.PARAGRAPH_TEXT) seq.push(next);
    }});
  }});
  seq.forEach(function (it, j) {{ f.moveItem(it.getIndex(), start + j); }});
}}

function buildOne_(spec) {{
  if (DriveApp.getFilesByName(spec.name).hasNext()) {{ Logger.log("exists, skipped: " + spec.name); return; }}
  var copy = DriveApp.getFileById(SOURCE_ID).makeCopy(spec.name);
  var f = FormApp.openById(copy.getId());
  f.setAcceptingResponses(false);
  f.deleteItem(find_(f, FIELD));
  f.moveItem(find_(f, EXPERT).getIndex(), 0);
  var p = f.addMultipleChoiceItem().setTitle(PRIOR).setChoiceValues(["Yes", "No", "Not sure"]).setRequired(true);
  f.moveItem(p.getIndex(), 1);
  var hz = find_(f, HORIZON_OLD).asMultipleChoiceItem();
  hz.setTitle(HORIZON.title).setChoiceValues(hz.getChoices().map(function (c) {{
    var v = c.getValue(); return v.indexOf("A. ") === 0 ? HORIZON.A : v.indexOf("B. ") === 0 ? HORIZON.B : v;
  }}));
  // the form's description (the test stand-in for FormApp has no setDescription)
  if (typeof f.setDescription === "function") f.setDescription(DESC);
  if (typeof f.setConfirmationMessage === "function") f.setConfirmationMessage(THANKS);
  // the questions whose two values are replaced, in the same A/B order
  CHOICES.forEach(function (s) {{
    var it = find_(f, s.title).asMultipleChoiceItem();
    if (s.newTitle) it.setTitle(s.newTitle);
    it.setChoiceValues(it.getChoices().map(function (c) {{ return s.map[c.getValue()] || c.getValue(); }}));
  }});
  find_(f, EMAIL.old).setTitle(EMAIL.title).setHelpText(EMAIL.help);
  // the share lost becomes its own question; departures and avoidance stay one question
  var bd = f.getItems(FormApp.ItemType.MULTIPLE_CHOICE).filter(function (it) {{
    return it.getTitle().indexOf(BUNDLE_PREFIX) === 0; }})[0].asMultipleChoiceItem();
  bd.setTitle(BUNDLE.title).setChoiceValues(bd.getChoices().map(function (c) {{
    return BUNDLE.map[c.getValue()] || c.getValue(); }}));
  var av = f.addMultipleChoiceItem().setTitle(AVOID.title).setChoiceValues(AVOID.choices).setRequired(false);
  f.addMultipleChoiceItem().setTitle(SHARE.title).setChoiceValues(SHARE.choices).setRequired(true);
  f.addParagraphTextItem().setTitle("Why? (optional)").setRequired(false);
  // the wealth question joins the optional page (without its own Why?); the opt-in says four
  var w = find_(f, SMALL.wealth), wNext = f.getItems()[w.getIndex() + 1];
  if (wNext && wNext.getType() === FormApp.ItemType.PARAGRAPH_TEXT) f.deleteItem(wNext);
  w.asMultipleChoiceItem().setRequired(false);
  var sp = find_(f, SMALL.old);
  sp.setTitle(SMALL.new);
  f.moveItem(w.getIndex(), sp.getIndex());   // lands right after the page break
  f.moveItem(av.getIndex(), sp.getIndex() + 1);   // avoidance first on the optional page, then wealth
  find_(f, CLOSE.old).setTitle(CLOSE.new);
  find_(f, CLOSE.support).asMultipleChoiceItem().setRequired(false);
  var oi = find_(f, SMALL.optin_old).asMultipleChoiceItem();
  oi.setTitle(SMALL.optin.title).setChoices(oi.getChoices().map(function (c) {{
    var v = SMALL.optin.choices[c.getValue()] || c.getValue(), g = c.getGotoPage();
    return g ? oi.createChoice(v, g) : oi.createChoice(v, c.getPageNavigationType());
  }}));
  regroup_(f);
  f.getItems(FormApp.ItemType.MULTIPLE_CHOICE).forEach(function (it) {{
    var mc = it.asMultipleChoiceItem(), ch = mc.getChoices().map(function (c) {{ return c.getValue(); }});
    if (ch.indexOf(UNSURE[0]) >= 0) mc.setChoiceValues(ch.map(function (c) {{ return c === UNSURE[0] ? UNSURE[1] : c; }}));
  }});
  if (spec.treated) {{
    var pb = f.addPageBreakItem().setTitle(TREAT.title).setHelpText(TREAT.help);
    f.moveItem(pb.getIndex(), 2);
    f.getItems(FormApp.ItemType.MULTIPLE_CHOICE).forEach(function (it) {{
      var mc = it.asMultipleChoiceItem(), ch = mc.getChoices().map(function (c) {{ return c.getValue(); }});
      if (ch.some(function (c) {{ return LABELS[c]; }})) {{
        mc.setChoiceValues(ch.map(function (c) {{ return LABELS[c] || c; }}));
      }}
    }});
  }}
  Logger.log(spec.name + "\\n  edit: " + f.getEditUrl() + "\\n  respond: " + f.getPublishedUrl());
  f.getItems().forEach(function (it, i) {{ Logger.log("  " + i + " " + it.getType() + " " + it.getTitle()); }});
}}

function buildExperiment() {{ FORMS.forEach(buildOne_); }}
""")
